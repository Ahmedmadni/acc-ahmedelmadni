/** Keep the answer choices in the same order in both languages, with varied answer positions. */
function placeAnswers(specs: CmaQuestionSpec[], positions: readonly (0 | 1 | 2 | 3)[]) {
  if (specs.length !== positions.length) throw new Error("CMA answer-position count mismatch");
  return specs.map((spec, index): CmaQuestionSpec => {
    const target = positions[index];
    const shift = (target - spec[7] + 4) % 4;
    const rotate = (choices: CmaQuestionSpec[5]): [string, string, string, string] => [
      choices[(4 - shift) % 4],
      choices[(5 - shift) % 4],
      choices[(6 - shift) % 4],
      choices[(7 - shift) % 4],
    ];
    return [
      spec[0],
      spec[1],
      spec[2],
      spec[3],
      spec[4],
      rotate(spec[5]),
      rotate(spec[6]),
      target,
      spec[8],
      spec[9],
    ];
  });
}

